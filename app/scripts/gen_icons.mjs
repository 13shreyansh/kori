// Collects every lucide icon name used as a string in src/ and writes src/ui/icons.gen.ts,
// so the bundle includes only those icons instead of the whole library.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import * as L from 'lucide-react';
const files = []; const walk = (d) => { for (const f of readdirSync(d)) { const p = d + '/' + f; statSync(p).isDirectory() ? walk(p) : /\.tsx?$/.test(f) && !f.endsWith('.gen.ts') && files.push(p); } }; walk('src');
const names = new Set(['Circle']);
for (const f of files) for (const m of readFileSync(f, 'utf8').matchAll(/['"]([A-Z][A-Za-z0-9]+)['"]/g)) if (m[1] in L && typeof L[m[1]] === 'object') names.add(m[1]);
const list = [...names].sort();
writeFileSync('src/ui/icons.gen.ts', `// generated by scripts/gen_icons.mjs\nimport { ${list.join(', ')} } from 'lucide-react';\nexport const ICONS = { ${list.join(', ')} };\n`);
console.log(list.length, 'icons');
